// Refreshes the pinned list of Discord's client sound files.
//
// Reads Discord's web client bundles, finds the hashed file each client
// sound is served as, and rewrites lib/src/data/discord/discord_sound_assets.dart.
// The sound files themselves are never downloaded or committed.
//
//   dart run tool/pin_discord_sounds.dart
//   dart run tool/pin_discord_sounds.dart --bundles <dir>
//
// With --bundles it reads the *.js chunks in that directory, such as the
// cache tool/inventory_discord_bundles.ps1 fills. Without it, it fetches
// https://discord.com/app and the chunks that page names.
import 'dart:io';

import 'package:flucord/src/domain/client_sounds.dart';

const soundAssetsPath = 'lib/src/data/discord/discord_sound_assets.dart';

/// The hashed file each of [names] is served as, read from the bundle texts.
///
/// One chunk maps `./<name>.mp3` to a module id; another holds the module,
/// which exports the public path plus the hashed file name. Throws a
/// [StateError] naming the sounds the bundles no longer lead to.
Map<String, String> pinSounds(
  Iterable<String> bundles,
  Iterable<String> names,
) {
  final moduleByName = <String, String>{};
  final fileByModule = <String, String>{};
  final mapEntry = RegExp(r'"\./([\w-]+)\.mp3":"?(\d+)"?');
  final module = RegExp(
    r'(\d+)\((\w+),\w+,(\w+)\)\{"use strict";\2\.exports=\3\.p\+"([\w.-]+\.mp3)"\}',
  );
  for (final text in bundles) {
    for (final match in mapEntry.allMatches(text)) {
      moduleByName[match[1]!] = match[2]!;
    }
    for (final match in module.allMatches(text)) {
      fileByModule[match[1]!] = match[4]!;
    }
  }
  final pinned = <String, String>{};
  final missing = <String>[];
  for (final name in names) {
    final file = fileByModule[moduleByName[name]];
    if (file == null) {
      missing.add(name);
    } else {
      pinned[name] = file;
    }
  }
  if (missing.isNotEmpty) {
    throw StateError('Not found in the bundles: ${missing.join(', ')}');
  }
  return pinned;
}

/// The Dart source of the pinned list.
String renderSoundAssets(Map<String, String> files) {
  final names = files.keys.toList()..sort();
  final lines = [for (final name in names) "  '$name': '${files[name]}',"];
  return '''
// Generated by tool/pin_discord_sounds.dart from Discord's web client
// bundles. Run that tool to refresh it; do not edit by hand.

/// Where Discord's web client loads its sound files from.
const discordSoundHost = 'https://discord.com/assets/';

/// Discord's sound module names, each with the hashed file it is served as.
const discordSoundFiles = <String, String>{
${lines.join('\n')}
};
''';
}

Future<void> main(List<String> arguments) async {
  final at = arguments.indexOf('--bundles');
  final bundles = at >= 0 && at + 1 < arguments.length
      ? _readBundles(Directory(arguments[at + 1]))
      : await _fetchBundles();
  final Map<String, String> pinned;
  try {
    pinned = pinSounds(bundles, ClientSound.values.map((s) => s.discordName));
  } on StateError catch (error) {
    stderr.writeln(error.message);
    exitCode = 1;
    return;
  }
  File(soundAssetsPath).writeAsStringSync(renderSoundAssets(pinned));
  stdout.writeln('Pinned ${pinned.length} sounds in $soundAssetsPath.');
}

List<String> _readBundles(Directory directory) => [
  for (final file in directory.listSync().whereType<File>())
    if (file.path.endsWith('.js')) file.readAsStringSync(),
];

Future<List<String>> _fetchBundles() async {
  final client = HttpClient();
  try {
    Future<String> get(String url) async {
      final response = await (await client.getUrl(Uri.parse(url))).close();
      if (response.statusCode != HttpStatus.ok) {
        throw HttpException(
          'status ${response.statusCode}',
          uri: Uri.parse(url),
        );
      }
      return response.transform(const SystemEncoding().decoder).join();
    }

    final page = await get('https://discord.com/app');
    final chunks = {
      for (final match in RegExp(r'/assets/[\w.-]+\.js').allMatches(page))
        match[0]!,
    };
    return Future.wait([
      for (final chunk in chunks) get('https://discord.com$chunk'),
    ]);
  } finally {
    client.close();
  }
}
